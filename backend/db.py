def set_meta(conn: Conn, key: str, value: str) -> None:
    conn.execute(
        "INSERT INTO meta(key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value",
        (key, value),
    )


def get_meta(conn: Conn, key: str, default: str | None = None) -> str | None:
    row = conn.execute("SELECT value FROM meta WHERE key = ?", (key,)).fetchone()
    return row["value"] if row else default


def get_sport(conn: Conn, slug: str):
    return conn.execute("SELECT * FROM sports WHERE slug = ?", (slug,)).fetchone()


def require_sport(conn: Conn, slug: str):
    row = get_sport(conn, slug)
    if not row:
        raise KeyError(slug)
    return row


