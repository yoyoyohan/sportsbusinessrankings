def _load_dotenv() -> None:
    env_path = ROOT / ".env"
    if not env_path.exists():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(key, value)


_load_dotenv()


def get_database_url() -> str | None:
    url = os.environ.get("DATABASE_URL") or os.environ.get("SUPABASE_DB_URL")
    if not url:
        return None
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    # Render is IPv4; Supabase transaction pooler (6543) is a poor fit for
    # a long-running web process. Session pooler uses 5432 on the same host.
    if os.environ.get("DATABASE_POOL_MODE") != "transaction" and ":6543/" in url:
        url = url.replace(":6543/", ":5432/")
    if "sslmode=" not in url and "supabase" in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"
    return url


class Conn:
    def __init__(self, raw: Any, dialect: str):
        self._raw = raw
        self.dialect = dialect

    def _adapt(self, sql: str) -> str:
        if self.dialect == "postgres":
            return sql.replace("?", "%s")
        return sql

    def execute(self, sql: str, params: Any = None):
        sql = self._adapt(sql)
        if params is None:
            cur = self._raw.execute(sql)
        else:
            cur = self._raw.execute(sql, tuple(params))
        return Cursor(cur)

    def executemany(self, sql: str, seq) -> None:
        sql = self._adapt(sql)
        rows = list(seq)
        if not rows:
            return
        if self.dialect == "postgres":
            with self._raw.cursor() as cur:
                cur.executemany(sql, rows)
            return
        self._raw.executemany(sql, rows)

    def executescript(self, script: str) -> None:
        if self.dialect == "postgres":
            for stmt in script.split(";"):
                stmt = stmt.strip()
                if stmt:
                    self._raw.execute(stmt)
            return
        self._raw.executescript(script)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        try:
            self._raw.rollback()
        except Exception:
            pass

    def close(self) -> None:
        self._raw.close()


class Cursor:
    def __init__(self, cur: Any):
        self._cur = cur
        self.lastrowid = getattr(cur, "lastrowid", None)

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()


def _sqlite_row(cursor, row):
    return {col[0]: row[i] for i, col in enumerate(cursor.description)}


def connect(db_path: Path | None = None) -> Conn:
    url = get_database_url()
    if url and db_path is None:
        return connect_postgres(url)
    return connect_sqlite(db_path)


def connect_sqlite(db_path: Path | None = None) -> Conn:
    path = db_path or DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    SOURCES_DIR.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(str(path), timeout=60)
    raw.row_factory = _sqlite_row
    raw.execute("PRAGMA foreign_keys = ON")
    raw.execute("PRAGMA journal_mode = WAL")
    return Conn(raw, "sqlite")


def connect_postgres(url: str | None = None) -> Conn:
    import psycopg
    from psycopg.rows import dict_row

    dsn = url or get_database_url()
    if not dsn:
        raise RuntimeError("DATABASE_URL is not set")
    SOURCES_DIR.mkdir(parents=True, exist_ok=True)
    raw = psycopg.connect(
        dsn,
        row_factory=dict_row,
        prepare_threshold=None,
        connect_timeout=10,
        keepalives=1,
        keepalives_idle=30,
        keepalives_interval=10,
        keepalives_count=3,
    )
    return Conn(raw, "postgres")


def _tables(conn: Conn) -> set[str]:
    if conn.dialect == "postgres":
        rows = conn.execute(
            "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
        ).fetchall()
        return {r["tablename"] for r in rows}
    return {
        r["name"]
        for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table'"
        ).fetchall()
    }


def _cols(conn: Conn, table: str) -> set[str]:
    if conn.dialect == "postgres":
        rows = conn.execute(
            """
            SELECT column_name FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = ?
            """,
            (table,),
        ).fetchall()
        return {r["column_name"] for r in rows}
    rows = conn._raw.execute(f"PRAGMA table_info({table})").fetchall()
    return {r["name"] for r in rows}


